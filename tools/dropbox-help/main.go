// Command dropbox-help derives the connector's input schemas from Dropbox's
// public OpenAPI export. Content-route arguments become ordinary named inputs;
// their session file path is supplied by the connector's help builder.
package main

import (
	"crypto/sha256"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/aibakery/houston-hub/tools/internal/helpschema"
)

type object = map[string]any

func obj(v any) object { m, _ := v.(map[string]any); return m }
func list(v any) []any { a, _ := v.([]any); return a }
func must(e error) {
	if e != nil {
		panic(e)
	}
}
func clone(v any) any {
	b, _ := json.Marshal(v)
	var out any
	must(json.Unmarshal(b, &out))
	return out
}
func main() {
	snapshot := flag.String("openapi", "", "local snapshot of https://docs.dropboxapi.com/openapi/dropbox-api.json")
	root := flag.String("root", ".", "Hub root")
	flag.Parse()
	raw, err := os.ReadFile(*snapshot)
	must(err)
	var spec object
	must(json.Unmarshal(raw, &spec))
	fixUnions(obj(obj(spec["components"])["schemas"]))
	b, err := os.ReadFile(filepath.Join(*root, "connectors/dropbox/connector.luau"))
	must(err)
	source := string(b)
	b, err = os.ReadFile(filepath.Join(*root, "tools/dropbox-help/examples.json"))
	must(err)
	var examples map[string][]object
	must(json.Unmarshal(b, &examples))
	schemas, cases := object{}, object{}
	for _, match := range regexp.MustCompile(`(?m)^\s*(\w+) = \{route = "([^"]+)"`).FindAllStringSubmatch(source, -1) {
		name, route := match[1], match[2]
		op := obj(clone(obj(obj(spec["paths"])["/2/"+route])["post"]))
		if op == nil {
			panic("missing route " + route)
		}
		style := "rpc"
		body := obj(obj(obj(op["requestBody"])["content"])["application/json"])["schema"]
		for _, p := range list(op["parameters"]) {
			param := obj(p)
			if param["name"] == "Dropbox-API-Arg" {
				body = param["schema"]
				style = "download"
				if route == "files/upload" {
					style = "upload"
				}
				op["requestBody"] = object{"content": object{"application/json": object{"schema": body}}}
			}
		}
		schema, err := helpschema.Input(spec, op, "", nil, nil, body != nil)
		if err != nil {
			panic(fmt.Errorf("%s: %w", name, err))
		}
		if body != nil {
			flattened, err := helpschema.FlattenObject(obj(list(schema["allOf"])[0]))
			must(err)
			if flattened["type"] != "object" || flattened["properties"] == nil {
				panic("unexpected argument schema " + name)
			}
			if schema["$defs"] != nil {
				flattened["$defs"] = schema["$defs"]
			}
			schema = flattened
		}
		if len(examples[name]) == 0 {
			panic("missing examples " + name)
		}
		schema["additionalProperties"] = false
		schema["examples"] = examples[name]
		schemas[name] = schema
		cases[name] = object{"route": route, "style": style, "void": body == nil}
	}
	if len(examples) != len(schemas) {
		panic("orphaned examples")
	}
	directory := filepath.Join(*root, "connectors/dropbox/lib")
	for name, v := range map[string]any{"schemas": schemas, "example-routes": cases} {
		b, err = json.MarshalIndent(v, "", "\t")
		must(err)
		header := fmt.Sprintf("-- Code generated by go run ./tools/dropbox-help -openapi <snapshot>; DO NOT EDIT.\n-- Source: https://docs.dropboxapi.com/openapi/dropbox-api.json\n-- SHA-256: %x\n-- Authored examples: tools/dropbox-help/examples.json\nreturn json.decode([====[\n", sha256.Sum256(raw))
		must(os.WriteFile(filepath.Join(directory, name+".luau"), []byte(header+string(b)+"\n]====])\n"), 0644))
	}
}

func fixUnions(defs object) {
	// This optional struct payload is flattened in Dropbox's wire format. The
	// OpenAPI export drops its fields; the canonical Stone definition retains them.
	// https://github.com/dropbox/dropbox-api-spec/blob/main/file_requests.stone
	update := obj(defs["file_requests_apiv2.UpdateFileRequestDeadline.update"])
	deadline := obj(defs["file_requests_apiv2.FileRequestDeadline"])
	for name, schema := range obj(deadline["properties"]) {
		obj(update["properties"])[name] = clone(schema)
	}
	update["dependentRequired"] = object{"allow_late_uploads": []any{"deadline"}}
	// Void unions accept either a tag string or an object with .tag. Payload-bearing
	// selectors require their payload (the export incorrectly makes it nullable).
	for name, value := range defs {
		s := obj(value)
		properties := obj(s["properties"])
		tag := obj(properties[".tag"])
		if tag == nil {
			continue
		}
		tagName, ok := tag["$ref"].(string)
		if !ok {
			continue
		}
		tags := list(obj(defs[strings.TrimPrefix(tagName, "#/components/schemas/")])["enum"])
		if len(tags) != 1 {
			continue
		}
		t, _ := tags[0].(string)
		if len(properties) == 1 {
			defs[name] = object{"anyOf": []any{s, object{"const": t}}}
			continue
		}
		if p := obj(properties[t]); p != nil {
			branches := list(p["oneOf"])
			if len(branches) == 2 && obj(branches[1])["type"] == "null" {
				p["oneOf"] = branches[:1]
			}
		}
	}
}
