// Command google-help bundles Google's discovery schemas for the operations
// declared by a connector. Network access is deliberately an authoring step;
// catalog validation and configured help stay offline.
package main

import (
	"crypto/sha256"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strconv"
	"strings"
)

type object = map[string]any

func obj(value any) object { result, _ := value.(map[string]any); return result }
func fatal(err error)      { fmt.Fprintln(os.Stderr, err); os.Exit(1) }

func main() {
	api := flag.String("api", "", "connector: gdrive, gmail, gcalendar, gdocs, gsheets, gslides or gforms")
	snapshot := flag.String("discovery", "", "local snapshot of Google's REST discovery document")
	root := flag.String("root", ".", "Hub repository root")
	flag.Parse()
	urls := map[string]string{
		"gdrive":    "https://www.googleapis.com/discovery/v1/apis/drive/v3/rest",
		"gcalendar": "https://www.googleapis.com/discovery/v1/apis/calendar/v3/rest",
		"gmail":     "https://gmail.googleapis.com/$discovery/rest?version=v1",
		"gdocs":     "https://docs.googleapis.com/$discovery/rest?version=v1",
		"gsheets":   "https://sheets.googleapis.com/$discovery/rest?version=v4",
		"gslides":   "https://slides.googleapis.com/$discovery/rest?version=v1",
		"gforms":    "https://forms.googleapis.com/$discovery/rest?version=v1",
	}
	if urls[*api] == "" || *snapshot == "" {
		fatal(fmt.Errorf("-api and -discovery are required"))
	}
	raw, err := os.ReadFile(*snapshot)
	if err != nil {
		fatal(err)
	}
	var spec object
	if err = json.Unmarshal(raw, &spec); err != nil {
		fatal(err)
	}
	source, err := os.ReadFile(filepath.Join(*root, "connectors", *api, "connector.luau"))
	if err != nil {
		fatal(err)
	}
	base := regexp.MustCompile(`(?m)^local API = "https://[^/]+([^"]*)"`).FindSubmatch(source)
	if len(base) != 2 {
		fatal(fmt.Errorf("connector API base missing"))
	}
	methods := map[string]object{}
	var collect func(object)
	collect = func(resource object) {
		for _, value := range obj(resource["methods"]) {
			m := obj(value)
			path := strings.ReplaceAll(fmt.Sprint(spec["servicePath"])+fmt.Sprint(m["path"]), "{+", "{")
			if *api == "gmail" {
				path = strings.ReplaceAll(path, "{userId}", "me")
			}
			path = "/" + strings.TrimPrefix(path, "/")
			path = strings.TrimPrefix(path, string(base[1]))
			if !strings.HasPrefix(path, "/") {
				path = "/" + path
			}
			methods[fmt.Sprint(m["httpMethod"])+" "+path] = m
		}
		for _, child := range obj(resource["resources"]) {
			collect(obj(child))
		}
	}
	collect(spec)
	converter := converter{api: *api, schemas: obj(spec["schemas"]), definitions: object{}}
	records := object{}
	pattern := regexp.MustCompile(`(?m)^\s*(\w+) = \{method = "(\w+)", path = "([^"]+)"`)
	for _, match := range pattern.FindAllStringSubmatch(string(source), -1) {
		name, route := match[1], match[2]+" "+match[3]
		method := methods[route]
		if method == nil {
			fatal(fmt.Errorf("%s: discovery method missing for %s", name, route))
		}
		parameters := object{}
		for key, value := range obj(spec["parameters"]) {
			schema, e := converter.schema(value)
			if e != nil {
				fatal(e)
			}
			parameters[key] = schema
		}
		required := []string{}
		for key, value := range obj(method["parameters"]) {
			schema, e := converter.schema(value)
			if e != nil {
				fatal(e)
			}
			parameters[key] = schema
			if obj(value)["required"] == true {
				required = append(required, key)
			}
		}
		slices.Sort(required)
		record := object{"parameters": parameters, "required": required}
		if request := obj(method["request"]); request != nil {
			ref, _ := request["$ref"].(string)
			body, e := converter.schema(converter.schemas[ref])
			if e != nil {
				fatal(fmt.Errorf("%s body: %w", name, e))
			}
			// Discovery's method-specific required annotations apply to the resource
			// body used by that method, e.g. Calendar event creation versus patching.
			mandatory := []string{}
			for key, value := range obj(obj(converter.schemas[ref])["properties"]) {
				for _, id := range list(obj(obj(value)["annotations"])["required"]) {
					if id == method["id"] {
						mandatory = append(mandatory, key)
					}
				}
			}
			if len(mandatory) > 0 {
				slices.Sort(mandatory)
				obj(body)["required"] = mandatory
			}
			record["body"] = body
		}
		records[name] = record
	}
	if len(records) == 0 {
		fatal(fmt.Errorf("no endpoint declarations found"))
	}
	data, err := json.MarshalIndent(object{"methods": records, "definitions": converter.definitions}, "", "\t")
	if err != nil {
		fatal(err)
	}
	output := fmt.Sprintf("-- Code generated by go run ./tools/google-help -api %s -discovery <snapshot>; DO NOT EDIT.\n-- Source: %s\n-- SHA-256: %x\nreturn json.decode([====[\n%s\n]====])\n", *api, urls[*api], sha256.Sum256(raw), data)
	directory := filepath.Join(*root, "connectors", *api, "lib")
	if err = os.MkdirAll(directory, 0755); err != nil {
		fatal(err)
	}
	if err = os.WriteFile(filepath.Join(directory, "discovery-schemas.luau"), []byte(output), 0644); err != nil {
		fatal(err)
	}
}

func list(value any) []any { values, _ := value.([]any); return values }

type converter struct {
	api         string
	schemas     map[string]any
	definitions object
}

// Discovery is based on an older JSON Schema dialect: required is a parameter
// boolean, bounds/defaults may be strings, and references are schema names.
// Convert these explicitly rather than letting a newer validator ignore them.
func (c *converter) schema(value any) (any, error) {
	source := obj(value)
	if source == nil {
		return nil, fmt.Errorf("missing discovery schema")
	}
	out := object{}
	for key, value := range source {
		switch key {
		case "id", "required", "location", "repeated", "annotations":
		case "$ref":
			name, ok := value.(string)
			if !ok || c.schemas[name] == nil {
				return nil, fmt.Errorf("unknown discovery reference %v", value)
			}
			out[key] = "#/$defs/" + strings.ReplaceAll(strings.ReplaceAll(name, "~", "~0"), "/", "~1")
			if _, seen := c.definitions[name]; !seen {
				c.definitions[name] = true
				schema, err := c.schema(c.schemas[name])
				if err != nil {
					return nil, err
				}
				c.definitions[name] = schema
			}
		case "properties":
			properties := object{}
			required := []string{}
			for name, property := range obj(value) {
				schema, err := c.schema(property)
				if err != nil {
					return nil, err
				}
				properties[name] = schema
				if obj(property)["required"] == true {
					required = append(required, name)
				}
			}
			out[key] = properties
			if len(required) > 0 {
				slices.Sort(required)
				out["required"] = required
			}
		case "items", "additionalProperties":
			if boolean, ok := value.(bool); ok {
				out[key] = boolean
				continue
			}
			schema, err := c.schema(value)
			if err != nil {
				return nil, err
			}
			out[key] = schema
		case "minimum", "maximum":
			if text, ok := value.(string); ok {
				number, err := strconv.ParseFloat(text, 64)
				if err != nil {
					return nil, fmt.Errorf("%s: %w", key, err)
				}
				out[key] = number
			} else {
				out[key] = value
			}
		case "default":
			text, ok := value.(string)
			if ok && (source["type"] == "integer" || source["type"] == "number" || source["type"] == "boolean") {
				var parsed any
				if err := json.Unmarshal([]byte(text), &parsed); err != nil {
					return nil, err
				}
				out[key] = parsed
			} else {
				out[key] = value
			}
		case "format":
			// Google's numeric and byte formats are wire descriptions, not the
			// standard date/time, URI, and email validation keywords.
			if slices.Contains([]string{"date", "date-time", "email", "hostname", "ipv4", "ipv6", "uri"}, fmt.Sprint(value)) {
				out[key] = value
			} else {
				out["x-google-format"] = value
			}
		case "type":
			if value != "any" {
				out[key] = value
			}
		default:
			out[key] = value
		}
	}
	if source["repeated"] == true {
		return object{"type": "array", "items": out}, nil
	}
	// Google editor batch requests are tagged by exactly one command field.
	// The discovery document describes every command but omits this union rule.
	if source["id"] == "Request" {
		properties := obj(out["properties"])
		names := []string{}
		for name := range properties {
			names = append(names, name)
		}
		slices.Sort(names)
		choices := []any{}
		for _, name := range names {
			choices = append(choices, object{"required": []string{name}})
		}
		if len(choices) > 0 {
			out["oneOf"] = choices
		}
	}
	if err := c.constraints(fmt.Sprint(source["id"]), out); err != nil {
		return nil, err
	}
	return out, nil
}
