// Command mercury-help combines published operation schemas with the maintained
// endpoint declarations. Snapshots and authored examples are explicit inputs;
// ordinary connector discovery and validation never contact Mercury.
package main

import (
	"crypto/sha256"
	"encoding/json"
	"flag"
	"fmt"
	"github.com/aibakery/houston-hub/tools/internal/helpschema"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

type object = map[string]any

func obj(v any) object { m, _ := v.(map[string]any); return m }
func must(e error) {
	if e != nil {
		panic(e)
	}
}
func main() {
	snapshot := flag.String("openapi", "", "merged local snapshot from the operation reference pages' OpenAPI definitions")
	root := flag.String("root", ".", "Hub root")
	flag.Parse()
	raw, err := os.ReadFile(*snapshot)
	must(err)
	var spec object
	must(json.Unmarshal(raw, &spec))
	b, err := os.ReadFile(filepath.Join(*root, "connectors/mercury/lib/endpoints.luau"))
	must(err)
	source := string(b)
	b, err = os.ReadFile(filepath.Join(*root, "tools/mercury-help/examples.json"))
	must(err)
	var examples map[string][]object
	must(json.Unmarshal(b, &examples))
	schemas := object{}
	declarations := regexp.MustCompile(`(?m)^\s*(\w+) = \{body = (true|false),.*?kind = "(\w+)".*?method = "(\w+)", path = "([^"]+)", query = \{(.*?)\}, required =`)
	queryFields := regexp.MustCompile(`(?:^|\}, )(?:(\w+)|\["([^"]+)"\]) = \{`)
	for _, match := range declarations.FindAllStringSubmatch(source, -1) {
		name, body, kind, method, path := match[1], match[2] == "true", match[3], match[4], match[5]
		op := obj(obj(obj(spec["paths"])[strings.TrimPrefix(path, "/api/v1")])[strings.ToLower(method)])
		if op == nil {
			panic("missing native operation " + name)
		}
		queries := []string{}
		for _, field := range queryFields.FindAllStringSubmatch(match[6], -1) {
			key := field[1]
			if key == "" {
				key = field[2]
			}
			queries = append(queries, key)
		}
		schema, err := helpschema.Input(spec, op, strings.TrimPrefix(path, "/api/v1"), queries, nil, body)
		if err != nil {
			panic(fmt.Errorf("%s: %w", name, err))
		}
		if body {
			schema["additionalProperties"] = true
		}
		if kind == "download" || kind == "upload" {
			schema["description"] = "This operation streams a session file; path is a local session file, not a provider URL."
		}
		if len(examples[name]) == 0 {
			panic("missing authored example " + name)
		}
		schema["examples"] = examples[name]
		schemas[name] = schema
	}
	if len(schemas) != len(examples) {
		panic("examples do not match actual endpoint declarations")
	}
	b, err = json.MarshalIndent(schemas, "", "\t")
	must(err)
	header := fmt.Sprintf("-- Code generated by go run ./tools/mercury-help -openapi <snapshot>; DO NOT EDIT.\n-- Source: https://docs.mercury.com/reference/<operation>.md (embedded OpenAPI definitions)\n-- SHA-256 of merged snapshot: %x\n-- Authored examples: tools/mercury-help/examples.json\nreturn json.decode([====[\n", sha256.Sum256(raw))
	must(os.WriteFile(filepath.Join(*root, "connectors/mercury/lib/schemas.luau"), []byte(header+string(b)+"\n]====])\n"), 0644))
}
