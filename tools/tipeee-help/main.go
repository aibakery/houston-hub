// Command tipeee-help records maintained routes for offline help-example fixtures.
// Native schemas and authored examples live in the bundle's lib directory.
package main

import (
	"encoding/json"
	"flag"
	"github.com/aibakery/houston-hub/tools/internal/helpschema"
	"os"
	"regexp"
)

func main() {
	flag.Parse()
	b, e := os.ReadFile("connectors/tipeee/connector.luau")
	if e != nil {
		panic(e)
	}
	source := string(b)
	routes := map[string]any{}
	for _, ep := range helpschema.Endpoints(source) {
		query, e := helpschema.Fields(source, ep.Definition, "query")
		if e != nil {
			panic(e)
		}
		body := ""
		if m := regexp.MustCompile(`body = "([^"]+)"`).FindStringSubmatch(ep.Definition); len(m) > 0 {
			body = m[1]
		}
		routes[ep.Name] = map[string]any{"method": ep.Method, "path": ep.Path, "query": query, "body": body}
	}
	b, e = json.MarshalIndent(routes, "", "\t")
	if e != nil {
		panic(e)
	}
	e = os.WriteFile("connectors/tipeee/lib/example-routes.luau", []byte("-- Code generated by go run ./tools/tipeee-help; DO NOT EDIT.\nreturn json.decode([====[\n"+string(b)+"\n]====])\n"), 0644)
	if e != nil {
		panic(e)
	}
}
