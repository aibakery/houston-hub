// Command prestashop-help extracts field metadata and XML association shapes
// from the official resource reference. Runtime help applies connector policy.
package main

import (
	"crypto/sha256"
	"encoding/json"
	"encoding/xml"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

type object = map[string]any

func must(e error) {
	if e != nil {
		panic(e)
	}
}

type node struct {
	XMLName  xml.Name
	Children []node `xml:",any"`
}

func main() {
	prefix := flag.String("prefix", "", "prefix for downloaded resource .md files")
	root := flag.String("root", ".", "Hub root")
	flag.Parse()
	if *prefix == "" {
		panic("provide -prefix for the downloaded resource .md snapshots")
	}
	result := object{}
	sources := ""
	for _, resource := range []string{"products", "customers", "order_carriers", "order_histories", "stock_availables"} {
		raw, e := os.ReadFile(*prefix + resource + ".md")
		must(e)
		text := string(raw)
		sources += fmt.Sprintf("-- https://raw.githubusercontent.com/PrestaShop/docs/9.x/webservice/resources/%s.md SHA-256: %x\n", resource, sha256.Sum256(raw))
		fields := object{}
		var headers []string
		for _, line := range strings.Split(text, "\n") {
			if !strings.HasPrefix(line, "|") {
				continue
			}
			parts := strings.Split(strings.Trim(line, "|"), "|")
			for i := range parts {
				parts[i] = strings.TrimSpace(parts[i])
			}
			if parts[0] == "Name" {
				headers = parts
				continue
			}
			if !strings.HasPrefix(parts[0], "**") {
				continue
			}
			if len(parts) != len(headers) {
				panic("unexpected resource table")
			}
			row := map[string]string{}
			for i, h := range headers {
				row[h] = parts[i]
			}
			field := object{"validator": row["Format"], "required": row["Required"] == "✔️", "writable": row["Writable"] != "❌", "description": row["Description"]}
			if row["Max size"] != "" {
				size, e := strconv.Atoi(row["Max size"])
				must(e)
				field["maxLength"] = size
			}
			fields[strings.Trim(row["Name"], "*")] = field
		}
		start := strings.Index(text, "<prestashop")
		end := strings.Index(text, "</prestashop>") + len("</prestashop>")
		if start < 0 || end < start {
			panic("missing XML")
		}
		var schema node
		must(xml.Unmarshal([]byte(text[start:end]), &schema))
		if len(schema.Children) != 1 {
			panic("unexpected resource XML")
		}
		associations := object{}
		for _, child := range schema.Children[0].Children {
			if child.XMLName.Local == "associations" {
				for _, association := range child.Children {
					if len(association.Children) != 1 {
						panic("unexpected association shape")
					}
					keys := []string{}
					for _, field := range association.Children[0].Children {
						keys = append(keys, field.XMLName.Local)
					}
					associations[association.XMLName.Local] = keys
				}
			}
			if len(child.Children) > 0 && child.Children[0].XMLName.Local == "language" {
				field, ok := fields[child.XMLName.Local].(map[string]any)
				if !ok {
					panic("missing translated field")
				}
				field["translated"] = true
			}
		}
		if len(fields) == 0 {
			panic("empty field table")
		}
		result[resource] = object{"fields": fields, "associations": associations}
	}
	b, e := json.MarshalIndent(result, "", "\t")
	must(e)
	directory := filepath.Join(*root, "connectors/prestashop/lib")
	must(os.MkdirAll(directory, 0755))
	must(os.WriteFile(filepath.Join(directory, "fields.luau"), []byte("-- Code generated by go run ./tools/prestashop-help -prefix <snapshot-prefix>; DO NOT EDIT.\n"+sources+"return json.decode([====[\n"+string(b)+"\n]====])\n"), 0644))
}
