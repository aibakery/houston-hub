// Command linear-help bundles the provider's GraphQL input types as JSON Schema.
// Fetch the provider snapshot explicitly; generation and connector discovery are offline.
package main

import (
	"crypto/sha256"
	_ "embed"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/vektah/gqlparser/v2/ast"
	"github.com/vektah/gqlparser/v2/parser"
)

type object = map[string]any

//go:embed LICENSE.linear
var schemaLicense string

type generator struct {
	types map[string]*ast.Definition
	defs  object
}

func main() {
	snapshot := flag.String("schema", "", "local snapshot of Linear's packages/sdk/src/schema.graphql")
	root := flag.String("root", ".", "Hub repository root")
	flag.Parse()
	if err := generate(*root, *snapshot); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(root, path string) error {
	raw, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	doc, err := parser.ParseSchema(&ast.Source{Name: path, Input: string(raw)})
	if err != nil {
		return err
	}
	g := generator{types: map[string]*ast.Definition{}, defs: object{}}
	for _, def := range doc.Definitions {
		g.types[def.Name] = def
	}
	connector, err := os.ReadFile(filepath.Join(root, "connectors/linear/connector.luau"))
	if err != nil {
		return err
	}
	// These are the argument declarations consumed by the connector's parameters()
	// and list(). Read the actual source so new operation types cannot drift silently.
	patterns := []string{`"\w+: (\w+)!?"`, `list\("(\w+)"`}
	for _, pattern := range patterns {
		for _, match := range regexp.MustCompile(pattern).FindAllStringSubmatch(string(connector), -1) {
			if _, err := g.named(match[1]); err != nil {
				return err
			}
		}
	}
	data, err := json.MarshalIndent(g.defs, "", "\t")
	if err != nil {
		return err
	}
	output := fmt.Sprintf(`-- Code generated by go run ./tools/linear-help -schema <snapshot>; DO NOT EDIT.
-- Source: https://github.com/linear/linear/blob/master/packages/sdk/src/schema.graphql
-- SHA-256: %x
-- Provider schema attribution:
--[====[
%s
]====]
local definitions = json.decode([====[
%s
]====])

-- Add only reachable types, preserving cycles through local references.
return function(schema)
	local reachable = {}
	local function visit(value)
		if type(value) ~= "table" then return end
		for key, child in value do
			if key == "$ref" then
				local name = string.match(child, "^#/$defs/(.+)$")
				assert(name and definitions[name], "unknown Linear input type " .. tostring(name))
				if not reachable[name] then
					reachable[name] = definitions[name]
					visit(definitions[name])
				end
			else visit(child) end
		end
	end
	visit(schema)
	if next(reachable) then schema["$defs"] = reachable end
	return schema
end
`, sha256.Sum256(raw), schemaLicense, data)
	dir := filepath.Join(root, "connectors/linear/lib")
	if err := os.MkdirAll(dir, 0755); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, "input-types.luau"), []byte(output), 0644)
}

func (g *generator) input(t *ast.Type) (object, error) {
	var schema object
	var err error
	if t.Elem != nil {
		item, e := g.input(t.Elem)
		if e != nil {
			return nil, e
		}
		// GraphQL also accepts a single value for a list, coercing it to one item.
		schema = object{"anyOf": []any{object{"type": "array", "items": item}, item}}
	} else {
		schema, err = g.named(t.NamedType)
	}
	if err != nil {
		return nil, err
	}
	if !t.NonNull {
		schema = object{"anyOf": []any{schema, object{"type": "null"}}}
	}
	return schema, nil
}

func (g *generator) named(name string) (object, error) {
	switch name {
	case "String", "ID":
		return object{"type": "string"}, nil
	case "Int":
		return object{"type": "integer", "minimum": -2147483648, "maximum": 2147483647}, nil
	case "Float":
		return object{"type": "number"}, nil
	case "Boolean":
		return object{"type": "boolean"}, nil
	}
	ref := object{"$ref": "#/$defs/" + name}
	if _, ok := g.defs[name]; ok {
		return ref, nil
	}
	d := g.types[name]
	if d == nil {
		return nil, fmt.Errorf("unknown GraphQL input type %s", name)
	}
	schema := object{}
	g.defs[name] = schema // Register before following recursive relation filters.
	if d.Description != "" {
		schema["description"] = d.Description
	}
	switch d.Kind {
	case ast.Enum:
		values := []string{}
		for _, value := range d.EnumValues {
			values = append(values, value.Name)
		}
		schema["type"], schema["enum"] = "string", values
	case ast.InputObject:
		properties, required := object{}, []string{}
		for _, field := range d.Fields {
			value, err := g.input(field.Type)
			if err != nil {
				return nil, err
			}
			if field.Description != "" {
				value["description"] = field.Description
			}
			if field.DefaultValue != nil {
				value["default"], err = field.DefaultValue.Value(nil)
				if err != nil {
					return nil, err
				}
			} else if field.Type.NonNull {
				required = append(required, field.Name)
			}
			properties[field.Name] = value
		}
		schema["type"], schema["properties"] = "object", properties
		// Unknown nested fields are forwarded for provider extensions, as before.
		if len(required) > 0 {
			schema["required"] = required
		}
		if d.Directives.ForName("oneOf") != nil {
			branches := []any{}
			for _, field := range d.Fields {
				branches = append(branches, object{"required": []string{field.Name}, "properties": object{field.Name: object{"not": object{"type": "null"}}}})
			}
			schema["oneOf"], schema["maxProperties"] = branches, 1
		}
	case ast.Scalar:
		switch name {
		case "JSONObject":
			schema["type"] = "object"
		case "JSON": // Arbitrary JSON, specified by the provider.
		case "UUID":
			schema["type"], schema["format"] = "string", "uuid"
		case "DateTime", "TimelessDate", "DateTimeOrDuration", "TimelessDateOrDuration", "Duration":
			schema["type"] = "string"
			if strings.HasSuffix(name, "OrDuration") {
				schema["description"] = d.Description + " ISO 8601 value or relative duration such as -P2W."
			}
		default:
			return nil, fmt.Errorf("unmapped provider scalar %s", name)
		}
	default:
		return nil, fmt.Errorf("%s is not an input type", name)
	}
	return ref, nil
}
