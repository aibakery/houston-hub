// Command dolibarr-help records native routes for offline help-example fixtures.
package main

import (
	"encoding/json"
	"flag"
	"github.com/aibakery/houston-hub/tools/internal/helpschema"
	"os"
	"regexp"
	"strings"
)

func must(e error) {
	if e != nil {
		panic(e)
	}
}
func main() {
	flag.Parse()
	b, e := os.ReadFile("connectors/dolibarr/connector.luau")
	must(e)
	source := string(b)
	starts := regexp.MustCompile(`\{name = "([^"]+)"`).FindAllStringSubmatchIndex(source, -1)
	routes := map[string]any{}
	for i, m := range starts {
		end := len(source)
		if i+1 < len(starts) {
			end = starts[i+1][0]
		}
		definition := source[m[0]:end]
		if close := strings.Index(definition, "\n}"); close >= 0 {
			definition = definition[:close]
		}
		name := source[m[2]:m[3]]
		literal := func(key string) string {
			m := regexp.MustCompile(key + ` = "([^"]+)"`).FindStringSubmatch(definition)
			if len(m) > 0 {
				return m[1]
			}
			return ""
		}
		method := literal("method")
		if method == "" {
			method = "GET"
		}
		query := []string{}
		list := strings.Contains(definition, "list =")
		if list {
			key := "paging"
			if !strings.Contains(definition, "paging =") {
				key = "query"
				v, e := helpschema.Fields(source, "query = PAGE", key)
				must(e)
				query = append(query, v...)
			} else {
				v, e := helpschema.Fields(source, definition, key)
				must(e)
				query = append(query, v...)
			}
		}
		for _, key := range []string{"list", "query"} {
			v, e := helpschema.Fields(source, definition, key)
			must(e)
			query = append(query, v...)
		}
		required, e := helpschema.Fields(source, definition, "required")
		must(e)
		routes[name] = map[string]any{"method": method, "path": literal("path"), "fields": literal("fields"), "query": query, "list": list, "required": required, "returns": literal("returns")}
	}
	b, e = json.MarshalIndent(routes, "", "\t")
	must(e)
	must(os.WriteFile("connectors/dolibarr/lib/example-routes.luau", []byte("-- Code generated by go run ./tools/dolibarr-help; DO NOT EDIT.\nreturn json.decode([====[\n"+string(b)+"\n]====])\n"), 0644))
}
