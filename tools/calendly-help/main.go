// Command calendly-help derives native input schemas from the public OpenAPI
// snapshot, narrowed to this connector's declarations and reviewed examples.
package main

import (
	"crypto/sha256"
	"encoding/json"
	"flag"
	"fmt"
	"maps"
	"net/url"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"

	"github.com/aibakery/houston-hub/tools/internal/helpschema"
)

type object = map[string]any

func obj(v any) object { m, _ := v.(map[string]any); return m }
func list(v any) []any { a, _ := v.([]any); return a }
func clone(v any) any  { b, _ := json.Marshal(v); var c any; must(json.Unmarshal(b, &c)); return c }
func must(e error) {
	if e != nil {
		panic(e)
	}
}

var placeholders = regexp.MustCompile(`\{([^}]+)\}`)
var quoted = regexp.MustCompile(`"([^"]+)"`)

type endpoint struct {
	name, method, path string
	query, required    []string
}

func fields(source, key string) []string {
	m := regexp.MustCompile(key + ` = \{([^}]+)\}`).FindStringSubmatch(source)
	var result []string
	if len(m) > 0 {
		for _, v := range quoted.FindAllStringSubmatch(m[1], -1) {
			result = append(result, v[1])
		}
	}
	return result
}
func declarations(source string) []endpoint {
	result := []endpoint{}
	for _, ep := range helpschema.Endpoints(source) {
		result = append(result, endpoint{ep.Name, ep.Method, ep.Path, fields(ep.Definition, "query"), fields(ep.Definition, "required")})
	}
	return result
}
func main() {
	snapshot := flag.String("openapi", "", "local snapshot of https://developer.calendly.com/openapi/calendly-api.json")
	root := flag.String("root", ".", "Hub root")
	flag.Parse()
	raw, err := os.ReadFile(*snapshot)
	must(err)
	var spec object
	must(json.Unmarshal(raw, &spec))
	code, err := os.ReadFile(filepath.Join(*root, "connectors/calendly/connector.luau"))
	must(err)
	exampleBytes, err := os.ReadFile(filepath.Join(*root, "tools/calendly-help/examples.json"))
	must(err)
	var examples map[string][]object
	must(json.Unmarshal(exampleBytes, &examples))
	type native struct {
		path string
		op   object
	}
	routes := map[string]native{}
	for path, v := range obj(spec["paths"]) {
		for method, op := range obj(v) {
			routes[strings.ToUpper(method)+" "+placeholders.ReplaceAllString(path, "{}")] = native{path, obj(op)}
		}
	}
	schemas, cases := object{}, object{}
	for _, ep := range declarations(string(code)) {
		n, ok := routes[ep.method+" "+placeholders.ReplaceAllString(ep.path, "{}")]
		if !ok {
			panic("missing route " + ep.name)
		}
		op := obj(clone(n.op))
		nativeParams, localParams := placeholders.FindAllStringSubmatch(n.path, -1), placeholders.FindAllStringSubmatch(ep.path, -1)
		for _, v := range list(op["parameters"]) {
			p := obj(v)
			if p["in"] == "path" {
				for i, name := range nativeParams {
					if p["name"] == name[1] {
						p["name"] = localParams[i][1]
						kind := strings.Split(strings.Split(ep.path, localParams[i][0])[0], "/")
						collection := kind[len(kind)-2]
						singular := strings.TrimSuffix(collection, "s")
						p["schema"] = object{"type": "string", "pattern": "^([A-Za-z0-9_-]+|https://api\\.calendly\\.com/(?:[^/]+/)*(?:" + collection + "|" + singular + ")/[A-Za-z0-9_-]+)$", "description": "Resource ID or a Calendly URI of this resource kind."}
					}
				}
			} else if p["in"] == "query" {
				s := obj(p["schema"])
				if d, ok := p["description"].(string); ok {
					s["description"] = d
				}
				if s["type"] == "array" {
					s["minItems"] = 1
					p["schema"] = object{"anyOf": []any{s, object{"type": "string", "minLength": 1, "description": "Comma-separated filter values."}}}
				}
				if ep.name == "listContacts" && p["name"] != "count" && p["name"] != "page_token" {
					p["schema"] = object{"anyOf": []any{s, object{"type": "array", "minItems": 1, "items": object{"type": "string"}}}}
				}
			}
		}
		body := ep.method == "POST" || ep.method == "PATCH" || ep.method == "PUT"
		schema, err := helpschema.Input(spec, op, ep.path, ep.query, ep.required, body)
		if err != nil {
			panic(fmt.Errorf("%s: %w", ep.name, err))
		}
		supplement(ep.name, schema)
		if len(examples[ep.name]) == 0 {
			panic("missing examples " + ep.name)
		}
		schema["examples"] = examples[ep.name]
		schemas[ep.name] = schema
		requests := []object{}
		for _, example := range examples[ep.name] {
			requests = append(requests, exampleRequest(ep, example))
		}
		cases[ep.name] = requests
	}
	for name := range examples {
		if schemas[name] == nil {
			panic("unknown example " + name)
		}
	}
	directory := filepath.Join(*root, "connectors/calendly/lib")
	must(os.MkdirAll(directory, 0755))
	for name, v := range map[string]any{"schemas": schemas, "example-requests": cases} {
		b, err := json.MarshalIndent(v, "", "\t")
		must(err)
		header := fmt.Sprintf("-- Code generated by go run ./tools/calendly-help -openapi <snapshot>; DO NOT EDIT.\n-- Source: https://developer.calendly.com/openapi/calendly-api.json\n-- SHA-256: %x\n-- Reviewed examples: tools/calendly-help/examples.json\nreturn json.decode([====[\n", sha256.Sum256(raw))
		must(os.WriteFile(filepath.Join(directory, name+".luau"), []byte(header+string(b)+"\n]====])\n"), 0644))
	}
}
func supplement(name string, s object) {
	if name == "createContact" || name == "updateContact" {
		body := obj(list(s["allOf"])[0])
		properties := obj(body["properties"])
		for _, field := range []string{"emails", "phone_numbers"} {
			obj(properties[field])["maxItems"] = 10
		}
		emails := obj(properties["emails"])
		emails["contains"] = object{"required": []string{"is_primary"}, "properties": object{"is_primary": object{"const": true}}}
		emails["minContains"], emails["maxContains"] = 1, 1
		if name == "updateContact" {
			choices := []any{}
			for _, field := range slices.Sorted(maps.Keys(properties)) {
				choices = append(choices, object{"required": []string{field}})
			}
			body["anyOf"], body["additionalProperties"] = choices, false
			properties["contact"] = true
		}
	}
	if name == "createSchedulingLink" {
		// The OpenAPI export types the numeric singleton as a string; the
		// provider reference's executable example sends max_event_count: 1.
		obj(s["$defs"])["SchedulingLinksPostRequestBodyContentApplicationJsonSchemaMaxEventCount"] = object{"const": 1}
	}
	// Provider-required relationships described in the reference but omitted from
	// its parameter list. Keep the connector's flat named-options convention.
	choices := map[string][]string{"listOrganizationMemberships": {"organization", "user"}, "listEventTypes": {"organization", "user"}, "listScheduledEvents": {"organization", "user", "group"}}
	if fields := choices[name]; fields != nil {
		branches := []any{}
		for _, field := range fields {
			branches = append(branches, object{"required": []string{field}, "properties": object{field: object{"type": "string", "minLength": 1}}})
		}
		s["anyOf"] = branches
	}
	if slices.Contains([]string{"listWebhookSubscriptions", "createWebhookSubscription", "getSampleWebhookData"}, name) {
		constraints := list(s["allOf"])
		for _, field := range []string{"user", "group"} {
			constraints = append(constraints, object{"if": object{"required": []string{"scope"}, "properties": object{"scope": object{"const": field}}}, "then": object{"required": []string{field}, "properties": object{field: object{"type": "string", "format": "uri"}}}})
		}
		s["allOf"] = constraints
	}
	if name == "createInviteeNoShow" {
		s["required"] = []string{"invitee"}
	}
}
func exampleRequest(ep endpoint, input object) object {
	args := obj(clone(input))
	path := ep.path
	for _, m := range placeholders.FindAllStringSubmatch(path, -1) {
		v, ok := args[m[1]]
		if !ok {
			panic(ep.name + " missing path " + m[1])
		}
		id := fmt.Sprint(v)
		if strings.HasPrefix(id, "https://api.calendly.com/") {
			parts := strings.Split(id, "/")
			id = parts[len(parts)-1]
		}
		path = strings.ReplaceAll(path, m[0], id)
		delete(args, m[1])
	}
	query := []string{}
	for _, field := range ep.query {
		if v := args[field]; v != nil {
			values := []any{v}
			if a, ok := v.([]any); ok {
				values = a
			}
			parts := []string{}
			for _, v := range values {
				parts = append(parts, strings.ReplaceAll(url.QueryEscape(fmt.Sprint(v)), "+", "%20"))
			}
			query = append(query, field+"="+strings.Join(parts, ","))
		}
		delete(args, field)
	}
	if len(query) > 0 {
		path += "?" + strings.Join(query, "&")
	}
	result := object{"method": ep.method, "url": "https://api.calendly.com" + path}
	if ep.method == "POST" || ep.method == "PATCH" || ep.method == "PUT" {
		result["body"] = args
	}
	return result
}
