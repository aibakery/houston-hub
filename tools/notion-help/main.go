// Command notion-help regenerates connector schemas from Notion's official OpenAPI
// snapshots and reviewed example inputs. Fetching snapshots is an explicit author task;
// normal validation and discovery are entirely offline.
package main

import (
	"crypto/sha256"
	"encoding/json"
	"flag"
	"fmt"
	"github.com/aibakery/houston-hub/tools/internal/helpschema"
	"os"
	"path/filepath"
	"reflect"
	"regexp"
	"slices"
	"strings"
)

type object = map[string]any

func main() {
	public := flag.String("public", "", "local snapshot of https://developers.notion.com/openapi.json")
	admin := flag.String("admin", "", "local snapshot of https://developers.notion.com/openapi-adminApi.json")
	root := flag.String("root", ".", "Hub repository root")
	flag.Parse()
	if *public == "" || *admin == "" {
		fatal(fmt.Errorf("both -public and -admin snapshots are required"))
	}
	examples, _, err := read(filepath.Join(*root, "tools/notion-help/examples.json"))
	if err != nil {
		fatal(err)
	}
	for _, source := range []struct{ file, module, url string }{
		{*public, "endpoints", "https://developers.notion.com/openapi.json"},
		{*admin, "admin", "https://developers.notion.com/openapi-adminApi.json"},
	} {
		spec, raw, err := read(source.file)
		if err != nil {
			fatal(err)
		}
		descriptor, err := os.ReadFile(filepath.Join(*root, "connectors/notion/lib", source.module+".luau"))
		if err != nil {
			fatal(err)
		}
		schemas := object{}
		// Endpoint declarations are one-line records. Reject omissions by checking the
		// resulting map against actual configured exports during catalog conformance.
		matches := regexp.MustCompile(`(?m)^\s*(\w+) = \{method = "(\w+)", path = "([^"]+)", read = (true|false), body = (true|false), query = \{([^}]*)\}, required = \{([^}]*)\}`).FindAllStringSubmatch(string(descriptor), -1)
		for _, match := range matches {
			name, method, path := match[1], match[2], match[3]
			if name == "sendFileUpload" {
				continue
			} // Native multipart helper, documented with the implementation.
			op := obj(obj(obj(spec["paths"])[strings.TrimPrefix(path, "/admin")])[strings.ToLower(method)])
			if op == nil {
				if name == "adminListAnalyticsReports" {
					continue
				} // Retained legacy route, absent in the current provider snapshot.
				fatal(fmt.Errorf("%s: %s %s missing from %s", name, method, path, source.url))
			}
			if name == "updateSession" {
				stream := obj(clone(op))
				params, _ := stream["parameters"].([]any)
				stream["parameters"] = append(params, object{"name": "path", "in": "path", "required": true, "schema": object{"type": "string", "minLength": 1, "description": "Session file to receive the complete raw SSE stream."}})
				schema, err := helpschema.Input(spec, stream, "/{path}", nil, nil, true)
				if err != nil {
					fatal(err)
				}
				schema["examples"] = examples["streamSession"]
				schemas["streamSession"] = schema
				op = obj(clone(op))
				body := obj(obj(obj(op["requestBody"])["content"])["application/json"])
				branches := obj(body["schema"])["oneOf"].([]any)
				var synchronous []any
				for _, branch := range branches {
					required, _ := obj(branch)["required"].([]any)
					if !slices.Contains(required, any("continue_from")) {
						synchronous = append(synchronous, branch)
					}
				}
				obj(body["schema"])["oneOf"] = synchronous
			}
			schema, err := helpschema.Input(spec, op, path, names(match[6]), names(match[7]), match[5] == "true")
			if err != nil {
				fatal(fmt.Errorf("%s: %w", name, err))
			}
			example, ok := examples[name].([]any)
			if !ok || len(example) == 0 {
				fatal(fmt.Errorf("%s: reviewed examples are required", name))
			}
			schema["examples"] = example
			schemas[name] = schema
		}
		definitions, references := object{}, object{}
		for name, value := range schemas {
			schema := obj(value)
			var refs []string
			for key, definition := range obj(schema["$defs"]) {
				if previous, exists := definitions[key]; exists && !reflect.DeepEqual(previous, definition) {
					fatal(fmt.Errorf("conflicting definition %s", key))
				}
				definitions[key] = definition
				refs = append(refs, key)
			}
			if len(refs) > 0 {
				slices.Sort(refs)
				references[name] = refs
			}
			delete(schema, "$defs")
		}
		data, err := json.MarshalIndent(object{"schemas": schemas, "definitions": definitions, "references": references}, "", "\t")
		if err != nil {
			fatal(err)
		}
		output := fmt.Sprintf("-- Code generated by go run ./tools/notion-help -public <snapshot> -admin <snapshot>; DO NOT EDIT.\n-- Source: %s\n-- SHA-256: %x\n-- Examples: tools/notion-help/examples.json. Local references retain provider nested schemas.\nlocal data = json.decode([====[\n%s\n]====])\n", source.url, sha256.Sum256(raw), data)
		output += `-- Store shared provider definitions once; each standalone schema gets only its reachable definitions.
for name, references in data.references do
	local definitions = {}
	for _, key in references do definitions[key] = data.definitions[key] end
	data.schemas[name]["$defs"] = definitions
end
return data.schemas
`
		if err := os.WriteFile(filepath.Join(*root, "connectors/notion/lib", source.module+"-schemas.luau"), []byte(output), 0644); err != nil {
			fatal(err)
		}
	}
}
func fatal(err error) { fmt.Fprintln(os.Stderr, err); os.Exit(1) }
func read(path string) (object, []byte, error) {
	b, e := os.ReadFile(path)
	if e != nil {
		return nil, nil, e
	}
	var v object
	e = json.Unmarshal(b, &v)
	return v, b, e
}
func obj(v any) object { m, _ := v.(map[string]any); return m }
func names(source string) []string {
	var out []string
	for _, m := range regexp.MustCompile(`"([^"]+)"`).FindAllStringSubmatch(source, -1) {
		out = append(out, m[1])
	}
	return out
}
func clone(v any) any { b, _ := json.Marshal(v); var out any; _ = json.Unmarshal(b, &out); return out }
