package main

import (
	"encoding/json"
	"github.com/aibakery/houston-hub/tools/internal/helpschema"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

func writeRoutes(root string) error {
	b, e := os.ReadFile(filepath.Join(root, "connectors/meta/connector.luau"))
	if e != nil {
		return e
	}
	source := string(b)
	if !strings.Contains(source, `local VERSION = "v26.0"`) {
		panic("connector API version differs from SDK")
	}
	constants := map[string]string{}
	for _, m := range regexp.MustCompile(`(?m)^local ([A-Z_]+) = ("[^"\n]*")`).FindAllStringSubmatch(source, -1) {
		v, e := strconv.Unquote(m[2])
		must(e)
		constants[m[1]] = v
	}
	routes := object{}
	for _, ep := range helpschema.Endpoints(source) {
		query, e := helpschema.Fields(source, ep.Definition, "query")
		if e != nil {
			return e
		}
		paging, e := helpschema.Fields(source, ep.Definition, "paging")
		if e != nil {
			return e
		}
		fields := ""
		if match := regexp.MustCompile(`fields = ((?:"[^"]*"|[A-Z_]+)(?:\s*\.\.\s*(?:"[^"]*"|[A-Z_]+))*)`).FindStringSubmatch(ep.Definition); len(match) > 0 {
			for _, part := range regexp.MustCompile(`"[^"]*"|[A-Z_]+`).FindAllString(match[1], -1) {
				if strings.HasPrefix(part, `"`) {
					v, e := strconv.Unquote(part)
					must(e)
					fields += v
				} else {
					v, ok := constants[part]
					if !ok {
						panic("unknown field constant " + part)
					}
					fields += v
				}
			}
		}
		host := "https://graph.facebook.com/v26.0"
		if strings.Contains(ep.Definition, "host = VIDEO_API") {
			host = "https://graph-video.facebook.com/v26.0"
		}
		routes[ep.Name] = object{"method": ep.Method, "path": ep.Path, "query": append(query, paging...), "fields": fields, "host": host, "paging": strings.Contains(ep.Definition, "paging ="), "upload": strings.Contains(ep.Definition, "upload = true")}
	}
	b, e = json.MarshalIndent(routes, "", "\t")
	if e != nil {
		return e
	}
	return os.WriteFile(filepath.Join(root, "connectors/meta/lib/example-routes.luau"), []byte("-- Code generated by go run ./tools/meta-help -sdk <facebook_business/adobjects>; DO NOT EDIT.\nreturn json.decode([====[\n"+string(b)+"\n]====])\n"), 0644)
}
