// Command wise-help extracts native request schemas from the public legacy
// documentation snapshot. Connector paths, queries and headers are added in Luau
// from the same declarations used by the request implementation.
package main

import (
	"crypto/sha256"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/aibakery/houston-hub/tools/internal/helpschema"
)

type object = map[string]any

func obj(v any) object { m, _ := v.(map[string]any); return m }
func must(e error) {
	if e != nil {
		panic(e)
	}
}
func clone(v any) any {
	b, e := json.Marshal(v)
	must(e)
	var out any
	must(json.Unmarshal(b, &out))
	return out
}

// Redoc stores Markdown descriptions as an AST. Preserve its text without
// copying renderer nodes into JSON Schema annotations.
func prose(v any) string {
	switch x := v.(type) {
	case string:
		return x
	case []any:
		var b strings.Builder
		for _, v := range x {
			b.WriteString(prose(v))
		}
		return b.String()
	case map[string]any:
		if s, ok := obj(x["attributes"])["content"].(string); ok {
			return s
		}
		return prose(x["children"])
	}
	return ""
}
func normalize(v any) any {
	s := obj(v)
	if s == nil {
		return v
	}
	if description, ok := s["description"]; ok {
		s["description"] = strings.TrimSpace(prose(description))
	}
	for _, key := range []string{"properties", "patternProperties", "$defs", "definitions"} {
		for name, child := range obj(s[key]) {
			obj(s[key])[name] = normalize(child)
		}
	}
	for _, key := range []string{"items", "additionalProperties", "unevaluatedProperties", "contains", "not", "if", "then", "else"} {
		if child, ok := s[key]; ok {
			s[key] = normalize(child)
		}
	}
	for _, key := range []string{"allOf", "anyOf", "oneOf", "prefixItems"} {
		if children, ok := s[key].([]any); ok {
			for i, child := range children {
				children[i] = normalize(child)
			}
		}
	}
	return v
}
func requests(v any, result map[string]string) {
	switch x := v.(type) {
	case map[string]any:
		if x["variant"] == "body" && x["schemaId"] != nil {
			p, _ := x["pointer"].(string)
			parts := strings.Split(p, "/")
			if len(parts) == 5 && parts[4] == "requestBody" {
				path := strings.ReplaceAll(strings.ReplaceAll(parts[2], "~1", "/"), "~0", "~")
				result[strings.ToUpper(parts[3])+" "+path] = x["schemaId"].(string)
			}
		}
		for _, c := range x {
			requests(c, result)
		}
	case []any:
		for _, c := range x {
			requests(c, result)
		}
	}
}
func main() {
	snapshot := flag.String("snapshot", "", "local https://docs.wise.com/page-data/shared/api-docs-api-reference/@legacy/index.yaml.json snapshot")
	root := flag.String("root", ".", "Hub root")
	flag.Parse()
	raw, e := os.ReadFile(*snapshot)
	must(e)
	var doc object
	must(json.Unmarshal(raw, &doc))
	bodies := map[string]string{}
	requests(doc["items"], bodies)
	store := obj(obj(doc["store"])["schemaStore"])
	defs := object{}
	for name, value := range store {
		if strings.HasPrefix(name, "components/schemas/") {
			defs[strings.TrimPrefix(name, "components/schemas/")] = normalize(clone(obj(value)["data"]))
		}
	}
	spec := object{"openapi": "3.1.0", "components": object{"schemas": defs}}
	code, e := os.ReadFile(filepath.Join(*root, "connectors/wise/connector.luau"))
	must(e)
	schemas := object{}
	for _, ep := range helpschema.Endpoints(string(code)) {
		if ep.Method != "POST" && ep.Method != "PATCH" {
			continue
		}
		key := bodies[ep.Method+" "+ep.Path]
		if key == "" {
			panic("missing body " + ep.Name)
		}
		body := normalize(clone(obj(store[key])["data"]))
		if ep.Name == "fundTransfer" {
			body = clone(defs["FundingRequestBalance"])
		}
		op := object{"requestBody": object{"content": object{"application/json": object{"schema": body}}}}
		input, e := helpschema.Input(spec, op, "", nil, nil, true)
		must(e)
		flattened, e := helpschema.FlattenObject(obj(input["allOf"].([]any)[0]))
		must(e)
		if flattened["type"] != "object" || flattened["properties"] == nil {
			panic("unexpected object schema " + ep.Name)
		}
		if input["$defs"] != nil {
			flattened["$defs"] = input["$defs"]
		}
		schemas[ep.Name] = flattened
	}
	directory := filepath.Join(*root, "connectors/wise/lib")
	must(os.MkdirAll(directory, 0755))
	b, e := json.MarshalIndent(schemas, "", "\t")
	must(e)
	header := fmt.Sprintf("-- Code generated by go run ./tools/wise-help -snapshot <snapshot>; DO NOT EDIT.\n-- Source: https://docs.wise.com/page-data/shared/api-docs-api-reference/@legacy/index.yaml.json\n-- SHA-256: %x\nreturn json.decode([====[\n", sha256.Sum256(raw))
	must(os.WriteFile(filepath.Join(directory, "body-schemas.luau"), []byte(header+string(b)+"\n]====])\n"), 0644))
}
